import { json } from "react-router";

/**
 * GET /api/tiktok
 *
 * TikTok OAuth 2.0 redirect callback. TikTok redirects the user's browser
 * here after they approve the app, with `code` and `state` query params.
 */
export async function loader({ request }) {
  const url = new URL(request.url);
  const state = url.searchParams.get("state") || "";
  const code = url.searchParams.get("code") || "";
  const error = url.searchParams.get("error");

  // ---------------------------------------------------------------
  // LOCAL DEV SHORTCUT (state starts with "local_")
  //
  // If the OAuth state was generated by a local dev machine it will
  // start with the "local_" prefix. In that case we do NOT call TikTok,
  // do NOT exchange `code` for an access token, do NOT store or log
  // anything – we just show the full URL so the developer can copy
  // `code` and `state` back into their local app to finish the flow.
  // ---------------------------------------------------------------
  if (state.startsWith("local_")) {
    const fullUrl = request.url;
    const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>TikTok callback – local dev</title>
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; max-width: 720px; margin: 48px auto; padding: 0 20px; color: #111; }
  h1 { font-size: 22px; margin: 0 0 8px; }
  p  { color: #555; line-height: 1.5; margin: 0 0 12px; }
  pre { background: #f5f5f5; border: 1px solid #e5e5e5; border-radius: 8px; padding: 14px; word-break: break-all; white-space: pre-wrap; font-size: 13px; margin: 0; }
</style>
</head>
<body>
  <h1>TikTok callback received</h1>
  <p>Copy the full address from your browser's address bar and paste it into your local app.</p>
  <pre>${escapeHtml(fullUrl)}</pre>
</body>
</html>`;
    return new Response(html, {
      status: 200,
      headers: { "Content-Type": "text/html; charset=utf-8" },
    });
  }

  // ---------------------------------------------------------------
  // PRODUCTION FLOW (state does NOT start with "local_")
  //
  // Exchange the authorization `code` for an access token via the
  // TikTok API, persist the token in the user's session, then redirect
  // back to the app's TikTok connect success page.
  // ---------------------------------------------------------------
  if (error) {
    return json({ ok: false, error }, { status: 400 });
  }
  if (!code) {
    return json({ ok: false, error: "missing_code" }, { status: 400 });
  }

  // TODO: implement the real TikTok token exchange here:
  //   POST https://open.tiktokapis.com/v2/oauth/token/
  //   { client_key, client_secret, code, grant_type: "authorization_code", redirect_uri }
  // Then:
  //   1. encrypt access_token + refresh_token + open_id and save in DB
  //   2. set the session cookie that links the TikTok account to the user
  //   3. redirect to /settings/tiktok-callback to show the success UI
  //
  // For now, acknowledge the callback. This placeholder will be replaced
  // with the real exchange in a follow-up PR; the local_ branch above is
  // independent of this work.
  return redirectToCallbackPage();
}

function redirectToCallbackPage() {
  const headers = new Headers();
  headers.set("Location", "/settings/tiktok-callback");
  return new Response(null, { status: 302, headers });
}

function escapeHtml(str) {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
